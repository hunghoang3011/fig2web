// emitter.js — wrap rendered screen bodies into a self-contained HTML bundle.
//
// Input : renderHtml() output { screenMeta, fontsUsed, imagesUsed }
// Output: files[] = index.html gallery + styles.css + screens/*.html + assets/*
//
// Assets: image fills are copied from the .fig container (images/<sha1>) into
// assets/<sha1>.<sniffed-ext> so the bundle works offline with no server.
import fs from 'node:fs';
import path from 'node:path';
import { esc } from './util.js';

/**
 * @param {{ screenMeta: Array, fontsUsed: Map, imagesUsed: Map }} rendered
 * @param {{ title?: string }} [opts]
 */
export function bundleHtml(rendered, opts = {}) {
  const { screenMeta, fontsUsed, imagesUsed } = rendered;
  const files = [];

  // ---------------- assets ----------------
  for (const [hash, { buf, ext }] of imagesUsed) {
    files.push({ path: `assets/${hash}.${ext}`, content: buf });
  }

  // ---------------- google fonts (best effort; SF Pro -> system fallback) ----------------
  const gfFamilies = [...fontsUsed.keys()].filter(f => f && !/(^|\b)(sf|apple|system)/i.test(f));
  const fontLink = gfFamilies.length
    ? `<link rel="stylesheet" href="https://fonts.googleapis.com/css2?${gfFamilies.map(f => `family=${encodeURIComponent(f)}:wght@300;400;500;600;700;800;900`).join('&')}&display=swap">`
    : '';

  // ---------------- screen pages ----------------
  for (const s of screenMeta) {
    files.push({
      path: `screens/${s.slug}.html`,
      content: `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${esc(s.name)}</title>
<link rel="preconnect" href="https://fonts.googleapis.com">${fontLink}
<link rel="stylesheet" href="../styles.css">
</head><body>
<div class="figscreen" style="width:${s.w}px;height:${s.h}px" data-page="${esc(s.page)}">${s.body}</div>
</body></html>`,
    });
  }

  // ---------------- shared stylesheet ----------------
  files.push({
    path: 'styles.css',
    content: `/* generated by fig2web */
*{margin:0;padding:0;box-sizing:border-box}
body{background:#1e1e22;display:flex;gap:24px;flex-wrap:wrap;padding:24px;align-items:flex-start}
.figscreen{position:relative;background:#fff;flex:none;overflow:hidden;box-shadow:0 8px 32px rgb(0 0 0/.35)}
`,
  });

  // ---------------- gallery ----------------
  const cards = screenMeta.map(s => `
<a class="card" href="screens/${s.slug}.html">
  <div class="thumb" data-w="${s.w}" data-h="${s.h}"><iframe src="screens/${s.slug}.html" loading="lazy" scrolling="no" tabindex="-1"></iframe></div>
  <span class="cap">${esc(s.name)}<small>${esc(s.page)} · ${s.w}×${s.h} · ${s.stats.nodes} nodes</small></span>
</a>`).join('\n');

  files.push({
    path: 'index.html',
    content: `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>fig2web — screens</title>
<style>
body{background:#17171a;color:#eee;font-family:-apple-system,sans-serif;margin:0;padding:32px}
h1{font-size:20px;margin:0 0 4px}
p.meta{color:#888;margin:0 0 24px;font-size:13px}
.grid{display:flex;flex-wrap:wrap;gap:20px}
.card{display:block;text-decoration:none;color:#eee;width:230px}
.thumb{height:360px;border-radius:10px;overflow:hidden;background:#26262b;box-shadow:0 4px 16px rgb(0 0 0/.4);position:relative}
.thumb iframe{border:0;transform-origin:0 0;pointer-events:none;position:absolute;top:0;left:0}
.cap{display:block;margin-top:8px;font-size:13px;line-height:1.4}
.cap small{display:block;color:#888;font-weight:400}
</style></head><body>
<h1>${esc(opts.title || 'Figma')} — rebuilt screens</h1>
<p class="meta">${screenMeta.length} screens · rebuilt offline from a .fig file (no Figma account needed)</p>
<div class="grid">${cards}
</div>
<script>
document.querySelectorAll('.thumb').forEach(el=>{
  const w=parseFloat(el.dataset.w), h=parseFloat(el.dataset.h);
  const s=Math.min(1, el.clientWidth/w);
  const f=el.querySelector('iframe');
  f.style.width=w+'px'; f.style.height=h+'px';
  f.style.transform='scale('+s+')';
  el.style.height=(h*s+16)+'px';
});
</script>
</body></html>`,
  });

  return { files };
}

/**
 * Write a files list ({path, content}) under outDir, creating directories.
 */
export function writeFiles(outDir, files) {
  const abs = path.resolve(outDir);
  for (const f of files) {
    const dest = path.join(abs, f.path);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, f.content);
  }
  return abs;
}
